-- ============================================================
-- Student Portal + Teacher Assignments
-- Additive only. No existing table, column, policy or function is
-- changed. All access goes through server route handlers using the
-- service role, so these tables have RLS enabled with no browser
-- policies.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Student accounts, sessions and login attempts
-- ------------------------------------------------------------

create table if not exists public.student_accounts (
  id                   uuid primary key default gen_random_uuid(),
  student_id           uuid not null unique references public.students(id) on delete cascade,
  password_hash        text not null,
  must_change_password boolean not null default true,
  is_active            boolean not null default true,
  last_login_at        timestamptz,
  password_changed_at  timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

create index if not exists student_accounts_student_idx
  on public.student_accounts(student_id);

create table if not exists public.student_sessions (
  id           uuid primary key default gen_random_uuid(),
  account_id   uuid not null references public.student_accounts(id) on delete cascade,
  token_hash   text not null unique,
  user_agent   text,
  ip_address   text,
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at   timestamptz not null
);

create index if not exists student_sessions_account_idx
  on public.student_sessions(account_id);
create index if not exists student_sessions_expires_idx
  on public.student_sessions(expires_at);

create table if not exists public.student_login_attempts (
  id              bigint generated by default as identity primary key,
  registration_no text not null,
  ip_address      text,
  success         boolean not null default false,
  attempted_at    timestamptz not null default now()
);

create index if not exists student_login_attempts_reg_idx
  on public.student_login_attempts(registration_no, attempted_at desc);
create index if not exists student_login_attempts_ip_idx
  on public.student_login_attempts(ip_address, attempted_at desc);

-- ------------------------------------------------------------
-- 2. Assignments
-- ------------------------------------------------------------

create table if not exists public.assignments (
  id                    uuid primary key default gen_random_uuid(),
  teacher_id            uuid references public.staff(id) on delete set null,
  subject_id            uuid not null references public.subjects(id) on delete cascade,
  class_id              uuid not null references public.school_classes(id) on delete cascade,
  stream_id             uuid not null references public.streams(id) on delete cascade,
  academic_year_id      text not null check (academic_year_id ~ '^[0-9]{4}$'),
  term                  int not null check (term in (1, 2)),
  title                 text not null,
  instructions          text not null default '',
  deadline              timestamptz,
  total_marks           numeric(6,2) not null default 100 check (total_marks >= 0),
  allow_late_submission boolean not null default false,
  status                text not null default 'published' check (status in ('draft', 'published', 'closed')),
  attachment_name       text,
  attachment_type       text,
  attachment_data       text,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists assignments_visibility_idx
  on public.assignments(subject_id, class_id, stream_id, status);
create index if not exists assignments_teacher_idx
  on public.assignments(teacher_id);
create index if not exists assignments_deadline_idx
  on public.assignments(deadline);

create table if not exists public.assignment_questions (
  id            uuid primary key default gen_random_uuid(),
  assignment_id uuid not null references public.assignments(id) on delete cascade,
  position      int not null default 1,
  question_type text not null check (question_type in ('essay', 'short_answer', 'mcq')),
  prompt        text not null,
  options       jsonb,
  correct_option int,
  marks         numeric(6,2) not null default 0 check (marks >= 0),
  created_at    timestamptz not null default now()
);

create index if not exists assignment_questions_assignment_idx
  on public.assignment_questions(assignment_id, position);

create table if not exists public.assignment_submissions (
  id              uuid primary key default gen_random_uuid(),
  assignment_id   uuid not null references public.assignments(id) on delete cascade,
  student_id      uuid not null references public.students(id) on delete cascade,
  status          text not null default 'draft' check (status in ('draft', 'submitted', 'marked')),
  started_at      timestamptz not null default now(),
  last_saved_at   timestamptz,
  submitted_at    timestamptz,
  is_late         boolean not null default false,
  total_score     numeric(6,2),
  feedback        text,
  attachment_name text,
  attachment_type text,
  attachment_data text,
  marked_at       timestamptz,
  marked_by       uuid references public.staff(id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (assignment_id, student_id)
);

create index if not exists assignment_submissions_assignment_idx
  on public.assignment_submissions(assignment_id, status);
create index if not exists assignment_submissions_student_idx
  on public.assignment_submissions(student_id);

create table if not exists public.assignment_answers (
  id            uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.assignment_submissions(id) on delete cascade,
  question_id   uuid not null references public.assignment_questions(id) on delete cascade,
  answer_html   text,
  answer_text   text,
  awarded_marks numeric(6,2),
  feedback      text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (submission_id, question_id)
);

create index if not exists assignment_answers_submission_idx
  on public.assignment_answers(submission_id);
create index if not exists assignment_answers_question_idx
  on public.assignment_answers(question_id);

-- ------------------------------------------------------------
-- 3. updated_at triggers (own function so this migration does not
--    depend on any other migration having run first)
-- ------------------------------------------------------------

create or replace function public.student_portal_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists student_accounts_set_updated_at on public.student_accounts;
create trigger student_accounts_set_updated_at
before update on public.student_accounts
for each row execute function public.student_portal_set_updated_at();

drop trigger if exists assignments_set_updated_at on public.assignments;
create trigger assignments_set_updated_at
before update on public.assignments
for each row execute function public.student_portal_set_updated_at();

drop trigger if exists assignment_submissions_set_updated_at on public.assignment_submissions;
create trigger assignment_submissions_set_updated_at
before update on public.assignment_submissions
for each row execute function public.student_portal_set_updated_at();

drop trigger if exists assignment_answers_set_updated_at on public.assignment_answers;
create trigger assignment_answers_set_updated_at
before update on public.assignment_answers
for each row execute function public.student_portal_set_updated_at();

-- ------------------------------------------------------------
-- 4. RLS: server-side only
-- ------------------------------------------------------------

alter table public.student_accounts        enable row level security;
alter table public.student_sessions        enable row level security;
alter table public.student_login_attempts  enable row level security;
alter table public.assignments             enable row level security;
alter table public.assignment_questions    enable row level security;
alter table public.assignment_submissions  enable row level security;
alter table public.assignment_answers      enable row level security;

comment on table public.student_accounts is
  'Student portal credentials. Access is server-side only (service role).';
comment on table public.assignments is
  'Homework sent by a teacher to one subject/class/stream.';
comment on table public.assignment_submissions is
  'One submission per student per assignment, with draft/submitted/marked status.';
